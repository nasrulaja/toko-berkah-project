-- ####################### 4. TANGGAL DIPINDAH KE OKTOBER #######################
-- =============================================================================
-- TOKO BERKAH — 04_ubah_tanggal_ke_oktober.sql
-- Memindahkan data dummy 03_data_dummy.sql dari November ke Oktober 2026
-- (mundur 1 bulan: 9-16 Nov -> 9-16 Okt).
--
-- Jalankan SEKALI, setelah 03_data_dummy.sql. Aman bila terlanjur dijalankan
-- dua kali: hanya baris yang masih bertanggal November yang diubah.
-- JANGAN jalankan 03_data_dummy.sql lagi sesudah ini (kode TRX-202611-... sudah
-- jadi TRX-202610-..., jadi 03 akan membuat data November baru lagi).
--
-- Tanggal dummy tersimpan di:
--   transaksi.waktu, kode_transaksi          (TRX-20261109-001 -> TRX-20261009-001)
--   struk.dicetak_pada, nomor_struk          (STR-20261109-001 -> STR-20261009-001)
--   stok_mutasi.waktu                        (penjualan, barang masuk, penyesuaian, stok awal toko)
--   rekap_penjualan.periode_mulai/akhir
--   tutup_buku.tanggal, ditutup_pada
-- =============================================================================

-- 1. Transaksi: waktu + kode (kode memuat tanggal)
UPDATE public.transaksi
SET waktu          = waktu - interval '1 month',
    kode_transaksi = replace(kode_transaksi, 'TRX-202611', 'TRX-202610')
WHERE waktu >= '2026-11-01' AND waktu < '2026-11-17'
  AND kode_transaksi LIKE 'TRX-202611%';

-- 2. Struk: waktu cetak + nomor struk
UPDATE public.struk
SET dicetak_pada = dicetak_pada - interval '1 month',
    nomor_struk  = replace(nomor_struk, 'STR-202611', 'STR-202610')
WHERE dicetak_pada >= '2026-11-01' AND dicetak_pada < '2026-11-17'
  AND nomor_struk LIKE 'STR-202611%';

-- 3. Riwayat stok dummy (stok awal toko 8 Nov, restock, penjualan, penyesuaian).
--    Baris 'Stok awal' dari 02_seed.sql tidak disentuh.
UPDATE public.stok_mutasi
SET waktu = waktu - interval '1 month'
WHERE waktu >= '2026-11-01' AND waktu < '2026-11-17'
  AND catatan IS DISTINCT FROM 'Stok awal';

-- 4. Rekap penjualan
UPDATE public.rekap_penjualan
SET periode_mulai = periode_mulai - interval '1 month',
    periode_akhir = periode_akhir - interval '1 month'
WHERE periode_mulai >= '2026-11-01' AND periode_mulai < '2026-11-17';

-- 5. Tutup buku
UPDATE public.tutup_buku
SET tanggal      = tanggal - interval '1 month',
    ditutup_pada = ditutup_pada - interval '1 month'
WHERE tanggal >= '2026-11-01' AND tanggal < '2026-11-17';

