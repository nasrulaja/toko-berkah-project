BEGIN;

-- Supabase sudah punya role anon/authenticated dan schema extensions;
-- di PostgreSQL biasa baris-baris ini membuatnya agar skrip tidak error.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')          THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
END $$;
CREATE SCHEMA IF NOT EXISTS extensions;

-- Pengaman: berhenti bila database sudah berisi transaksi
DO $$
BEGIN
  IF to_regclass('public.transaksi') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM public.transaksi LIMIT 1) THEN
      RAISE EXCEPTION 'Database ini sudah berisi transaksi. File ini hanya untuk database kosong; tidak ada yang diubah.';
    END IF;
  END IF;
END $$;

-- ############################ 1. SKEMA ############################
-- =============================================================================
-- TOKO BERKAH — 01_schema.sql
-- Skema database Supabase (PostgreSQL) sesuai PRD "Sistem Kasir Berbasis Scan
-- Barcode pada UMKM Toko Berkah". Dipakai bersama oleh Web, Android, Desktop.
--
-- Cara pakai: Supabase Dashboard > SQL Editor > New query > tempel > Run.
-- Urutan: 01_schema.sql dulu, lalu 02_seed.sql.
-- Aman dijalankan ulang (IF NOT EXISTS / DROP POLICY IF EXISTS).
--
-- Catatan kompatibilitas dengan kode yang sudah ada di repo:
--  * Nama tabel & kolom persis seperti yang dibaca js/core/api.js (web) dan
--    Data/Supa.cs (desktop).
--  * Primary key memakai "GENERATED BY DEFAULT AS IDENTITY": id dibuat otomatis
--    bila tidak dikirim, tetapi aplikasi (mis. desktop saat kirim tutup_buku)
--    tetap boleh mengirim id sendiri.
--  * Stok TIDAK diubah oleh trigger. Aplikasi sudah mengurangi/menambah stok
--    sendiri lewat PATCH produk + insert stok_mutasi; trigger akan membuat
--    stok terhitung dua kali.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. ROLES — hak akses akun
-- ---------------------------------------------------------------------------
create table if not exists public.roles (
  id                  bigint generated by default as identity primary key,
  nama                text    not null default '',
  bisa_kelola_barang  boolean not null default false,  -- produk, kategori, stok
  bisa_transaksi      boolean not null default false   -- transaksi penjualan
);

-- ---------------------------------------------------------------------------
-- 2. USERS — pengguna sistem (login web / android / desktop)
-- ---------------------------------------------------------------------------
create table if not exists public.users (
  id             bigint generated by default as identity primary key,
  nama           text   not null,
  email          text   not null unique,
  password_hash  text   not null,
  role_id        bigint not null references public.roles(id),
  created_at     timestamp not null default now()
);
create index if not exists users_role_id_idx on public.users(role_id);

-- ---------------------------------------------------------------------------
-- 3. KATEGORI — kelompok barang
-- ---------------------------------------------------------------------------
create table if not exists public.kategori (
  id          bigint generated by default as identity primary key,
  nama        text   not null unique,
  created_at  timestamp not null default now()
);

-- ---------------------------------------------------------------------------
-- 4. PRODUK — barang dagangan
-- ---------------------------------------------------------------------------
create table if not exists public.produk (
  id            bigint generated by default as identity primary key,
  nama          text    not null,
  barcode       text    unique,                                    -- EAN-13, boleh kosong
  harga_jual    integer not null default 0 check (harga_jual >= 0),
  harga_beli    integer not null default 0 check (harga_beli >= 0), -- opsional, dipakai web untuk hitung laba
  stok          integer not null default 0,
  stok_minimum  integer not null default 0 check (stok_minimum >= 0),
  kategori_id   bigint  references public.kategori(id) on delete set null,
  created_at    timestamp not null default now(),
  updated_at    timestamp not null default now()
);
create index if not exists produk_kategori_id_idx on public.produk(kategori_id);
create index if not exists produk_nama_idx        on public.produk(lower(nama));

-- updated_at otomatis saat baris diubah
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists produk_set_updated_at on public.produk;
create trigger produk_set_updated_at
  before update on public.produk
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 5. REKAP_PENJUALAN — rekap per periode (harian / mingguan / bulanan)
-- ---------------------------------------------------------------------------
create table if not exists public.rekap_penjualan (
  id                bigint generated by default as identity primary key,
  jenis_periode     text      not null check (jenis_periode in ('harian','mingguan','bulanan')),
  periode_mulai     timestamp not null,
  periode_akhir     timestamp not null,
  jumlah_transaksi  integer   not null default 0,
  total_penjualan   integer   not null default 0,
  total_sebelumnya  integer   not null default 0,
  tren              text      not null default 'tetap' check (tren in ('naik','turun','tetap')),
  check (periode_akhir >= periode_mulai)
);
create index if not exists rekap_periode_idx on public.rekap_penjualan(jenis_periode, periode_mulai);

-- ---------------------------------------------------------------------------
-- 6. TRANSAKSI — data utama penjualan
-- ---------------------------------------------------------------------------
create table if not exists public.transaksi (
  id              bigint generated by default as identity primary key,
  kode_transaksi  text      not null unique,   -- juga untuk cegah duplikat saat sinkron offline
  waktu           timestamp not null default now(),
  total           integer   not null default 0 check (total >= 0),
  uang_diterima   integer   not null default 0 check (uang_diterima >= 0),
  kembalian       integer   not null default 0,
  user_id         bigint    references public.users(id),
  rekap_id        bigint    references public.rekap_penjualan(id) on delete set null,
  status          text      not null default 'berhasil' check (status in ('berhasil','gagal'))
);
create index if not exists transaksi_waktu_idx    on public.transaksi(waktu);
create index if not exists transaksi_user_id_idx  on public.transaksi(user_id);
create index if not exists transaksi_rekap_id_idx on public.transaksi(rekap_id);

-- ---------------------------------------------------------------------------
-- 7. STRUK — bukti cetak transaksi
-- ---------------------------------------------------------------------------
create table if not exists public.struk (
  id            bigint generated by default as identity primary key,
  transaksi_id  bigint not null references public.transaksi(id) on delete cascade,
  nomor_struk   text   not null unique,
  nama_toko     text   not null default 'Toko Berkah',
  alamat_toko   text,
  pesan_footer  text   default 'Terima kasih sudah berbelanja',
  status_cetak  text   not null default 'belum' check (status_cetak in ('belum','berhasil','gagal')),
  dicetak_pada  timestamp
);
create index if not exists struk_transaksi_id_idx on public.struk(transaksi_id);

-- ---------------------------------------------------------------------------
-- 8. DETAIL_TRANSAKSI — rincian item per transaksi
--    nama_produk & harga_jual adalah salinan saat transaksi (snapshot).
-- ---------------------------------------------------------------------------
create table if not exists public.detail_transaksi (
  id            bigint generated by default as identity primary key,
  transaksi_id  bigint  not null references public.transaksi(id) on delete cascade,
  struk_id      bigint  references public.struk(id) on delete set null,
  produk_id     bigint  references public.produk(id) on delete set null,
  nama_produk   text    not null,
  harga_jual    integer not null check (harga_jual >= 0),
  jumlah        integer not null check (jumlah > 0),
  subtotal      integer not null check (subtotal >= 0)   -- harga_jual x jumlah
);
create index if not exists detail_transaksi_transaksi_idx on public.detail_transaksi(transaksi_id);
create index if not exists detail_transaksi_produk_idx    on public.detail_transaksi(produk_id);
create index if not exists detail_transaksi_struk_idx     on public.detail_transaksi(struk_id);

-- ---------------------------------------------------------------------------
-- 9. STOK_MUTASI — riwayat pergerakan stok
--    jumlah: + menambah, - mengurangi.
--    jenis : jual (dari PRD), masuk, penyesuaian, keluar (barang keluar
--            non-penjualan; dipakai web untuk mencatat penjualan/keluar).
-- ---------------------------------------------------------------------------
create table if not exists public.stok_mutasi (
  id            bigint generated by default as identity primary key,
  produk_id     bigint  not null references public.produk(id) on delete cascade,
  jenis         text    not null check (jenis in ('jual','masuk','penyesuaian','keluar')),
  jumlah        integer not null,
  stok_sebelum  integer not null,
  stok_sesudah  integer not null,
  harga_kulak   integer check (harga_kulak is null or harga_kulak >= 0),  -- jenis masuk
  transaksi_id  bigint  references public.transaksi(id) on delete set null, -- jenis jual
  catatan       text,                                                      -- wajib utk penyesuaian
  waktu         timestamp not null default now(),
  user_id       bigint  references public.users(id),
  constraint stok_mutasi_catatan_penyesuaian
    check (jenis <> 'penyesuaian' or nullif(btrim(catatan), '') is not null)
);
create index if not exists stok_mutasi_produk_waktu_idx on public.stok_mutasi(produk_id, waktu desc);
create index if not exists stok_mutasi_waktu_idx        on public.stok_mutasi(waktu);
create index if not exists stok_mutasi_transaksi_idx    on public.stok_mutasi(transaksi_id);

-- ---------------------------------------------------------------------------
-- 10. TUTUP_BUKU — hasil tutup buku harian (dibuat di Desktop, dilihat di Web)
--     tanggal bertipe date: web membandingkan dengan string 'YYYY-MM-DD'.
-- ---------------------------------------------------------------------------
create table if not exists public.tutup_buku (
  id               bigint generated by default as identity primary key,
  tanggal          date    not null unique,           -- satu tutup buku per hari
  total_penjualan  integer not null default 0,
  uang_di_laci     integer not null default 0,
  selisih          integer not null default 0,        -- uang_di_laci - total_penjualan
  status           text    not null default 'sesuai' check (status in ('sesuai','kurang','lebih')),
  catatan          text,
  user_id          bigint  references public.users(id),
  ditutup_pada     timestamp not null default now()
);

-- ---------------------------------------------------------------------------
-- VIEW bantu (opsional, tidak dipakai kode lama)
-- ---------------------------------------------------------------------------
create or replace view public.v_stok_menipis
with (security_invoker = true) as
select p.id, p.nama, p.barcode, k.nama as kategori, p.stok, p.stok_minimum
from public.produk p
left join public.kategori k on k.id = p.kategori_id
where p.stok <= p.stok_minimum
order by (p.stok - p.stok_minimum), p.nama;

create or replace view public.v_produk_lengkap
with (security_invoker = true) as
select p.id, p.nama, p.barcode, p.harga_jual, p.harga_beli, p.stok, p.stok_minimum,
       p.kategori_id, k.nama as kategori
from public.produk p
left join public.kategori k on k.id = p.kategori_id;

-- =============================================================================
-- ROW LEVEL SECURITY
-- Web, Android & Desktop memakai publishable (anon) key dan login-nya tabel
-- `users` buatan sendiri (bukan Supabase Auth), jadi policy di bawah memberi
-- akses ke role `anon`/`authenticated`. Ini cukup untuk project TA/demo.
-- Untuk produksi: pindah ke Supabase Auth lalu batasi policy per auth.uid().
-- =============================================================================
do $$
declare t text;
begin
  foreach t in array array['roles','users','kategori','produk','rekap_penjualan',
                           'transaksi','struk','detail_transaksi','stok_mutasi','tutup_buku']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_app_all', t);
    execute format(
      'create policy %I on public.%I for all to anon, authenticated using (true) with check (true)',
      t || '_app_all', t);
  end loop;
end $$;

-- Data master & akun dikelola lewat dashboard/SQL, bukan dari aplikasi:
-- (kode web/desktop memang tidak menulis users & roles)
drop policy if exists roles_app_all  on public.roles;
drop policy if exists roles_app_read on public.roles;
create policy roles_app_read on public.roles for select to anon, authenticated using (true);

drop policy if exists users_app_all  on public.users;
drop policy if exists users_app_read on public.users;
create policy users_app_read on public.users for select to anon, authenticated using (true);

-- Hash password tidak boleh terbaca lewat API publik.
-- Web memang hanya memilih kolom id,nama,email,role_id.
revoke all on public.users from anon, authenticated;
grant select (id, nama, email, role_id, created_at) on public.users to anon, authenticated;

-- Hak dasar tabel lain untuk API (PostgREST)
grant usage on schema public to anon, authenticated;
grant select on public.roles to anon, authenticated;
grant select, insert, update, delete on
  public.kategori, public.produk, public.rekap_penjualan, public.transaksi,
  public.struk, public.detail_transaksi, public.stok_mutasi, public.tutup_buku
  to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
grant select on public.v_stok_menipis, public.v_produk_lengkap to anon, authenticated;

